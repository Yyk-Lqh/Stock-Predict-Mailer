"""Bundle console feature modules for the existing four-asset HTTP contract."""
from pathlib import Path

WEB = Path(__file__).resolve().parents[1] / "src" / "stock_predict_mailer" / "control" / "web"
MODULES = ("memory", "workspace", "knowledge", "pony-door", "pony-model", "pony-screen", "pony-reference", "pony-rig", "pony-children", "pony-progress", "hall-data", "hall-wall", "market-feed", "pony-office", "analysis-input", "mail-recipients", "composer-controls")


def build():
    return "/* Generated by scripts/build_console.py; edit web/modules/*.js. */\n" + "\n".join(
        (WEB / "modules" / f"{name}.js").read_text(encoding="utf-8") for name in MODULES
    )


if __name__ == "__main__":
    import sys

    output = WEB / "memory.js"
    expected = build()
    if "--check" in sys.argv:
        if output.read_text(encoding="utf-8") != expected:
            raise SystemExit("Console bundle is stale; run python scripts/build_console.py")
        print("Console bundle is current")
    else:
        output.write_text(expected, encoding="utf-8", newline="\n")
