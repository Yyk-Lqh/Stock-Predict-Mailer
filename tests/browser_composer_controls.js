/* Run with gstack browse against the disposable :8768 browser fixture only. */
(async()=>{
  const assert=(ok,label)=>{if(!ok)throw Error(label);};
  assert(location.port==='8768','Use the disposable fixture');
  const wait=async fn=>{for(let i=0;i<100;i++){if(await fn())return;await new Promise(resolve=>setTimeout(resolve,100));}throw Error('Timed out');};
  window.__composerCheck={state:'running',stage:'boot'};
  await wait(()=>document.body.dataset.view==='analysis'&&window.ComposerControls);
  window.__composerCheck.stage='models';
  const suffix=Date.now();
  const first=await api('models','POST',{name:`Composer fixture A ${suffix}`,provider:'mock'});
  const second=await api('models','POST',{name:`Composer fixture B ${suffix}`,provider:'mock'});
  await refresh();
  const previous=await api('settings');
  $('composer-model').click();
  const choices=[...document.querySelectorAll('.composer-menu-row')];
  assert(choices.some(n=>n.textContent===first.name)&&choices.some(n=>n.textContent===second.name),'configured model choices');
  choices.find(n=>n.textContent===second.name).click();
  await wait(()=>$('composer-model').textContent.includes(second.name));
  const saved=await api('settings');
  assert(saved.default_model_id===second.id,'model selection reaches backend');
  assert(JSON.stringify(saved.agents)===JSON.stringify(previous.agents),'model selection preserves role configuration');
  window.__composerCheck.stage='effort';
  $('composer-effort').click();
  const slider=document.querySelector('.composer-popover input[type=range]'),field=$('task-effort'),before=field.value;
  let inputEvents=0,changeEvents=0;
  const onInput=event=>{if(event.target===field)inputEvents++;},onChange=event=>{if(event.target===field)changeEvents++;};
  $('task-form').addEventListener('input',onInput);$('task-form').addEventListener('change',onChange);
  assert(Number(slider.step)<.01,'thumb supports continuous movement between semantic levels');
  for(let i=0;i<120;i++){slider.value=String(i/119*3.2);slider.dispatchEvent(new Event('input',{bubbles:true}));}
  assert(field.value===before&&inputEvents===0&&changeEvents===0,'dragging does not refresh or save the form');
  await new Promise(requestAnimationFrame);
  assert(slider.style.getPropertyValue('--effort-fill')==='80%','track paints the continuous drag position');
  slider.value='2';slider.dispatchEvent(new Event('input',{bubbles:true}));slider.dispatchEvent(new Event('change',{bubbles:true}));
  assert(inputEvents===1&&changeEvents===1,'release commits exactly one form change');
  slider.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true,cancelable:true}));
  assert(field.value==='extreme'&&slider.value==='3','keyboard moves a whole semantic level');
  slider.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true,cancelable:true}));
  $('task-form').removeEventListener('input',onInput);$('task-form').removeEventListener('change',onChange);
  assert($('task-effort').value==='high'&&taskControlsDirty,'slider sets actual task execution control');
  assert(slider.getAttribute('aria-valuetext')==='高','accessible effort value');
  slider.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  assert(document.querySelector('.composer-popover').hidden,'Escape closes popup');
  window.__composerCheck.stage='permissions';
  $('composer-permission').click();
  [...document.querySelectorAll('.composer-menu-row')].find(n=>n.textContent==='完成后发送授权邮件').click();
  assert($('task-notify').checked,'mail permission links existing request field');
  const recipient=document.querySelector('.composer-popover input[type=email]');recipient.value='preview@example.invalid';recipient.dispatchEvent(new Event('input',{bubbles:true}));
  assert($('task-recipient').value===recipient.value,'recipient field synchronization');
  [...document.querySelectorAll('.composer-menu-row')].find(n=>n.textContent==='仅分析与生成报告').click();
  assert(!$('task-notify').checked,'analysis-only mode disables mail');
  ComposerControls.close();$('analysis-data-open').click();document.querySelector('.composer-menu-row').click();
  assert(!$('report-inspector').hidden&&!$('analysis-pane-input').hidden,'plus menu opens real analysis data');
  assert($('analysis-send').form===$('task-form'),'arrow retains native form submission');
  const supported=!!(window.SpeechRecognition||window.webkitSpeechRecognition);
  assert($('composer-voice').disabled===!supported,'voice capability reflects browser support');
  Workbench.inspector(false);
  window.__composerCheck={state:'done',model:second.id,effort:$('task-effort').value,voiceSupported:supported,note:'No microphone recording or external model invocation.'};
})().catch(error=>{window.__composerCheck={state:'failed',stage:window.__composerCheck?.stage,error:error.message};});
