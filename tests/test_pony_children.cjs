const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync('src/stock_predict_mailer/control/web/modules/pony-children.js','utf8'),context);
const tracker=new context.PonyChildren.Tracker();
const equal=(a,b)=>assert.deepEqual(JSON.parse(JSON.stringify(a)),JSON.parse(JSON.stringify(b)));

let state=tracker.update('risk','child-risk','running');
assert.equal(state.message,'等待 风险分析 返回');
equal(state.pending,[{role:'risk',childId:'child-risk'}]);
state=tracker.update('risk','child-risk','running');
equal(state.pending,[{role:'risk',childId:'child-risk'}],'repeated running event updates instead of duplicating a child');
state=tracker.update('prediction','child-prediction','running');
assert.equal(state.message,'等待 风险分析、预测分析 返回');
state=tracker.update('risk',null,'completed');
assert.equal(state.message,'等待 预测分析 返回','one returning child does not clear the other wait');
equal(state.pending,[{role:'prediction',childId:'child-prediction'}]);
state=tracker.update('prediction',null,'failed');
assert.equal(state.message,'预测分析失败 · 主 Agent 继续');
equal(state.pending,[]);
tracker.reset();
state=tracker.update('advice','child-advice','running');
assert.equal(state.message,'等待 建议生成 返回');
state=tracker.update('advice',null,'canceled');
assert.equal(state.message,'建议生成已取消 · 主 Agent 继续');
tracker.reset();
tracker.update('risk','child-risk-3','running');
tracker.update('prediction','child-prediction-2','running');
state=tracker.update('risk',null,'failed');
assert.equal(state.message,'等待 预测分析 返回 · 风险分析失败','failure remains visible while another child is running');
state=tracker.update('prediction',null,'completed');
assert.equal(state.message,'风险分析失败 · 主 Agent 继续','one child failure is not lost when the others complete');
state=tracker.update('charts','unexpected','running');
assert.equal(state,null,'non-child steps do not enter the child tracker');
tracker.update('risk','child-risk-2','running');
tracker.reset();
equal(tracker.snapshot(),[],'task reset clears previous child identities');
console.log('Child progress passed: pending queue, partial returns, terminal states, role filtering and reset.');
